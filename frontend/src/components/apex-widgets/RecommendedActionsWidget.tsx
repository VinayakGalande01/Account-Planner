'use client';

// RecommendedActionsWidget — APEX pipeline Level 7 widget.
// Renders backend-generated "what's next" suggestions as animated
// pill/chip buttons; clicking a chip re-submits it as a user query.
// Sections in this file:
//   - Props/types
//   - Helpers (priority icon lookup)
//   - Render (divider, label, animated chip grid)

import React from 'react';
import { motion } from 'framer-motion';
import type { RecommendedAction } from '../../types/responseContract';

// --- SECTION: Props ---
interface RecommendedActionsWidgetProps {
  actions: RecommendedAction[];
  onActionClick?: (action: RecommendedAction) => void;
}

/**
 * Level 7: Copilot Next-Step Suggestions.
 * Renders contextual recommended actions as interactive chip/pill buttons
 * with staggered fade-in animation and hover effects.
 *
 * Design Rule: Actions are generated by the backend based on context.
 *              Frontend handles rendering, animation, and click routing.
 *              Clicking a chip sends it as a new user query.
 */
export function RecommendedActionsWidget({ actions, onActionClick }: RecommendedActionsWidgetProps) {
  if (!actions || actions.length === 0) return null;

  // --- SECTION: Helpers ---
  const getPriorityIcon = (priority?: string) => {
    switch (priority) {
      case 'high':
        return '⚡';
      case 'low':
        return '○';
      default:
        return '→';
    }
  };

  // --- SECTION: Render ---
  return (
    <div className="apex-recommended-actions">
      {/* Gradient divider */}
      <div className="apex-recommended-actions-divider" />

      <div className="apex-section-label" style={{ marginTop: '12px' }}>
        WHAT WOULD YOU LIKE TO DO NEXT?
      </div>

      <div className="apex-recommended-actions-grid">
        {actions.map((action, i) => (
          <motion.button
            key={action.action || i}
            initial={{ opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{
              duration: 0.35,
              delay: i * 0.08,
              ease: 'easeOut',
            }}
            className={`apex-action-chip ${
              action.priority === 'high' ? 'apex-action-chip--high' : ''
            }`}
            onClick={() => onActionClick?.(action)}
            title={action.description || action.title}
          >
            <span className="apex-action-chip-icon">
              {getPriorityIcon(action.priority)}
            </span>
            <span>{action.title}</span>
          </motion.button>
        ))}
      </div>
    </div>
  );
}
